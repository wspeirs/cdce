//! Tunes CDCE eval terms against labeled quiet positions with pliers.
//!
//! Usage: `cdce-tune <labeled.epd> [epochs]`
//! Format: `FEN c9 "1-0";` / `"0-1"` / `"1/2-1/2"` per line.
//! Every 10th position is held out; loss is reported for both splits.

mod features;
mod tune_eval;

use std::fs;

use gears::games::chess::Board;
use gears::general::board::{BoardHelpers, Strictness};
use pliers::eval::{Eval, WeightsInterpretation};
use pliers::gd::{loss, optimize_dataset, Dataset, DefaultOptimizer, Float, Optimizer, Outcome, Weight, Weights};

use tune_eval::CdceTuneEval;

const DEFAULT_EPOCHS: usize = 200;
const HOLDOUT_EVERY: usize = 10;

fn parse_outcome(tag: &str) -> Result<f64, String> {
    match tag {
        "1-0" => Ok(1.0),
        "0-1" => Ok(0.0),
        "1/2-1/2" => Ok(0.5),
        other => Err(format!("unknown result tag '{other}'")),
    }
}

/// Splits one EPD line into a 6-field FEN and its outcome.
///
/// The quiet set is `FEN c9 "1/2-1/2";`: the first four fields are the board, side, castling and en-passant;
/// `c9` is an EPD opcode. Clocks are not used by the eval, so they are set to `0 1`.
fn parse_line(line: &str, line_num: usize) -> Result<(String, f64), String> {
    let (fen, rest) = line.split_once('"').ok_or_else(|| format!("line {line_num}: missing result tag"))?;
    let tag = rest.split('"').next().unwrap_or_default();
    let outcome = parse_outcome(tag).map_err(|e| format!("line {line_num}: {e}"))?;
    let fields: Vec<&str> = fen.split_whitespace().take(4).collect();
    if fields.len() != 4 {
        return Err(format!("line {line_num}: expected 4 FEN fields, got {}", fields.len()));
    }
    Ok((format!("{} 0 1", fields.join(" ")), outcome))
}

/// Builds `(train, holdout)` datasets from the labeled EPD file.
fn load(path: &str) -> Result<(Dataset, Dataset), String> {
    let text = fs::read_to_string(path).map_err(|e| format!("reading {path}: {e}"))?;
    let num_weights = CdceTuneEval::num_weights();
    let mut train = Dataset::new(num_weights);
    let mut holdout = Dataset::new(num_weights);
    for (i, line) in text.lines().enumerate() {
        if line.trim().is_empty() {
            continue;
        }
        let (fen, y) = parse_line(line, i + 1)?;
        let board =
            Board::from_fen(&fen, Strictness::Relaxed).map_err(|e| format!("line {}: bad FEN '{fen}': {e}", i + 1))?;
        let target = if i % HOLDOUT_EVERY == 0 { &mut holdout } else { &mut train };
        CdceTuneEval::extract_features(&board, Outcome::new(y as Float), target);
    }
    Ok((train, holdout))
}

/// Writes the fitted phased weights as `cdce_eval::tuned_weights` (MG/EG per feature index, centipawns).
fn emit_weights(path: &str, weights: &Weights, epochs: usize, input: &str) -> Result<(), String> {
    let nf = cdce_eval::layout::NUM_FEATURES;
    if weights.0.len() != 2 * nf {
        return Err(format!("expected {} weights, got {}", 2 * nf, weights.0.len()));
    }
    let mg: Vec<String> = (0..nf).map(|f| (weights.0[2 * f].0.round() as i32).to_string()).collect();
    let eg: Vec<String> = (0..nf).map(|f| (weights.0[2 * f + 1].0.round() as i32).to_string()).collect();
    let text = format!(
        "//! Generated by cdce-tune from {input} ({epochs} epochs). Do not edit by hand.\n\
         //!\n\
         //! Phased weights per feature index (see `layout`), centipawns.\n\n\
         pub const MG: [i32; {nf}] = [{}];\n\
         pub const EG: [i32; {nf}] = [{}];\n",
        mg.join(", "),
        eg.join(", ")
    );
    fs::write(path, text).map_err(|e| format!("writing {path}: {e}"))
}

/// Standard `CdceParams` values in the tuner's interleaved `(mg, eg)` weight layout (cp units).
fn standard_weights() -> Weights {
    let v = cdce_eval::TunedValues::from_params(&cdce_eval::CdceParams::standard());
    let mut w = Vec::with_capacity(2 * cdce_eval::layout::NUM_FEATURES);
    for f in 0..cdce_eval::layout::NUM_FEATURES {
        w.push(Weight(v.mg[f] as Float));
        w.push(Weight(v.eg[f] as Float));
    }
    Weights(w)
}

fn main() -> Result<(), String> {
    let args: Vec<String> = std::env::args().collect();
    let positional: Vec<&String> = args.iter().skip(1).filter(|a| !a.starts_with("--")).collect();
    let path = positional.first().ok_or("usage: cdce-tune <labeled.epd> [epochs] [out.rs] [--seed-standard|--standard-check]")?;
    let epochs = match positional.get(1) {
        Some(e) => e.parse().map_err(|err| format!("bad epochs '{e}': {err}"))?,
        None => DEFAULT_EPOCHS,
    };

    let (mut train, holdout) = load(path)?;
    let e = CdceTuneEval { seed_standard: args.iter().any(|a| a == "--seed-standard") };
    println!("train positions: {}, holdout positions: {}", train.num_datapoints(), holdout.num_datapoints());
    if train.num_datapoints() == 0 || holdout.num_datapoints() == 0 {
        return Err("no positions loaded; check the input file".to_string());
    }

    let zero = Weights(vec![Weight(0.0); CdceTuneEval::num_weights()]);
    let baseline_train = loss(&zero, train.as_batch());
    let baseline_holdout = loss(&zero, holdout.as_batch());
    println!("zero weights: train loss {baseline_train:.6}, holdout loss {baseline_holdout:.6}");

    let batch = train.as_batch();
    let scale = e.eval_scale().to_scaling_factor(batch, &e);
    println!("eval scale: {scale:?}");
    if args.iter().any(|a| a == "--standard-check") {
        // Loss of the standard CdceParams weights through the same loss path as the fit (cp / scale).
        let std_cp = standard_weights();
        let std_unscaled = std_cp * (1.0 / scale);
        println!("standard weights: train loss {:.6}, holdout loss {:.6}", loss(&std_unscaled, train.as_batch()), loss(&std_unscaled, holdout.as_batch()));
        return Ok(());
    }
    // `--adam` drops AdamW weight decay (lambda=1e-2 by default), which pulls every weight toward zero.
    let mut optimizer = if args.iter().any(|a| a == "--adam") { DefaultOptimizer::adam(batch) } else { DefaultOptimizer::new(batch) };
    let weights = optimize_dataset(&mut train, epochs, &e, scale, &mut optimizer);

    // `optimize_dataset` returns weights * scale_factor (display units); `loss` takes the unscaled internal weights.
    let unscaled = weights.clone() * (1.0 / scale);
    let tuned_train = loss(&unscaled, train.as_batch());
    let tuned_holdout = loss(&unscaled, holdout.as_batch());
    println!("tuned ({epochs} epochs): train loss {tuned_train:.6}, holdout loss {tuned_holdout:.6}");
    println!("{}", pliers::eval::display(&e, &weights, &[]));
    if let Some(out) = positional.get(2) {
        emit_weights(out, &weights, epochs, path)?;
        println!("wrote {out}");
    }
    if tuned_holdout >= baseline_holdout {
        return Err(format!("holdout loss did not decrease: {baseline_holdout:.6} -> {tuned_holdout:.6}"));
    }
    Ok(())
}
